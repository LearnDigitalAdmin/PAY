export function renderTranscriptHtml(snap: Snapshot, o: { lang: Lang; requestId: string; generatedAt: Date }): string {
  const t = T[o.lang];
  const s = snap.summary;
  const st = s.statement;
  const gen = `${dayLabel(o.generatedAt.toISOString().slice(0, 10), o.lang)}`;
  const due = dayLabel(s.remittance.dueDate, o.lang);

  const items = (kind: "income" | "deduction") =>
    st.items.filter((i) => i.kind === kind).map((i) => `<tr><td>${esc(i.label)}</td><td class="r ${kind === "income" ? "inc" : "ded"}">${kind === "income" ? "" : "− "}${esc(i.amount.d)}</td></tr>`).join("");

  const rows = snap.tenants.map((r) => `
    <tr>
      <td>${esc(r.name)}</td><td>${esc(r.unit ?? "")}</td>
      <td class="r">${esc(r.rent.d)}</td><td class="r">${esc(r.paid.d)}</td><td class="r">${esc(r.balance.d)}</td>
      <td class="st-${r.status}">${esc(t.s[r.status])}</td>
      <td>${r.paidOn ? esc(dayLabel(r.paidOn, o.lang)) + (r.paidOnTime === false ? ` <span class="muted">(${esc(t.late)})</span>` : "") : ""}</td>
    </tr>`).join("");

  return `<!doctype html><html lang="${o.lang}"><head><meta charset="utf-8"><title>${esc(t.title)} ${esc(snap.ownerId)} ${esc(snap.month)}</title><style>${CSS}</style></head><body>
  <div class="top">
    <div><div class="brand">${esc(t.brand)}</div><div class="tag">${esc(t.tagline)}</div></div>
    <div class="meta" style="text-align:right"><div>${esc(t.generated)}: <b>${esc(gen)}</b></div><div>${esc(t.ref)}: <b>${esc(o.requestId.slice(0, 8).toUpperCase())}</b></div></div>
  </div>
  <h1>${esc(t.title)}: ${esc(monthLabel(snap.month, o.lang))}</h1>
  <div class="meta">${esc(t.property)}: <b>${esc(snap.property.name)}</b>${snap.property.address ? ` · ${esc(snap.property.address)}` : ""} · ${esc(t.owner)}: <b>${esc(snap.ownerId)}</b></div>
  <div style="margin-top:8px"><span class="badge ${st.source === "agent" ? "agent" : "est"}">${esc(st.source === "agent" ? t.agentStatement : t.estimate)}</span></div>
  ${st.source === "estimate" ? `<div class="note">${esc(t.estimateNote)}</div>` : ""}

  <h2>${esc(t.summary)}</h2>
  <div class="cards">
    <div class="card"><div class="l">${esc(t.billed)}</div><div class="v">${esc(s.billed.d)}</div></div>
    <div class="card"><div class="l">${esc(t.collected)}</div><div class="v">${esc(s.collected.d)}</div></div>
    <div class="card"><div class="l">${esc(t.pending)}</div><div class="v">${esc(s.pending.d)}</div></div>
    <div class="card"><div class="l">${esc(t.rate)}</div><div class="v">${esc(s.collectionRatePct.d)}</div></div>
  </div>
  <div class="muted" style="margin-top:6px">${esc(t.occupancy)}: ${esc(s.tenants.occupiedUnits.d)} / ${esc(snap.property.maxUnits.d)} ${esc(t.units)} (${esc(s.tenants.occupancyPct.d)})</div>

  <h2>${esc(t.statement)}</h2>
  <table>
    <tr><th>${esc(t.income)}</th><th class="r"></th></tr>${items("income")}
    <tr class="tot"><td>${esc(t.total)} ${esc(t.income.toLowerCase())}</td><td class="r inc">${esc(st.income.d)}</td></tr>
    <tr><th>${esc(t.deductions)}</th><th class="r"></th></tr>${items("deduction")}
    <tr class="tot"><td>${esc(t.total)} ${esc(t.deductions.toLowerCase())}</td><td class="r ded">− ${esc(st.deductions.d)}</td></tr>
    <tr class="net"><td>${esc(t.net)}</td><td class="r">${esc(st.netPayable.d)}</td></tr>
  </table>
  <div class="muted" style="margin-top:5px">${esc(t.commissionNote)}</div>
  ${st.notes ? `<h2>${esc(t.notes)}</h2><div>${esc(st.notes)}</div>` : ""}

  <h2>${esc(t.remittance)} · ${esc(t.dueBy)} ${esc(due)}</h2>
  <table>
    <tr><td>${esc(t.byDue)}</td><td class="r">${esc(s.remittance.collectedByDue.d)}</td><td>${esc(t.netByDue)}</td><td class="r"><b>${esc(s.remittance.netByDue.d)}</b></td></tr>
    <tr><td>${esc(t.afterDue)}</td><td class="r">${esc(s.remittance.collectedAfterDue.d)}</td><td>${esc(t.netAfterDue)}</td><td class="r"><b>${esc(s.remittance.netAfterDue.d)}</b></td></tr>
  </table>

  <h2>${esc(t.tenants)}</h2>
  <table>
    <tr><th>${esc(t.tenant)}</th><th>${esc(t.unit)}</th><th class="r">${esc(t.rent)}</th><th class="r">${esc(t.paid)}</th><th class="r">${esc(t.balance)}</th><th>${esc(t.status)}</th><th>${esc(t.paidOn)}</th></tr>
    ${rows}
  </table>
  <div class="muted" style="margin-top:14px">${esc(t.footer)}</div>
  </body></html>`;
}
